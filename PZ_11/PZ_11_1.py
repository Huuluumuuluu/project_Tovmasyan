# Даны средние значения температур за каждый месяц в году.
# Найти минимальное и максимальное значения температур за год.
# Вывести значения температур по временам года.

def task1(temps):
    # исходные данные
    print(f"Температуры: {temps}")
    print(f"Мин: {min(temps)}, Макс: {max(temps)}")
    # сезоны через списковые включения
    idx = {"Зима": [11,0,1], "Весна": [2,3,4], "Лето": [5,6,7], "Осень": [8,9,10]}
    for season, ind in idx.items():
        print(f"{season}: {[temps[i] for i in ind]}")
