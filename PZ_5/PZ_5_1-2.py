#вещественные параметры, являющиеся одновременно входными и выходными).
#Используя четыре вызова этой функции, найти минимальное и максимальное из
#данных чисел A, B, C, D.
def sum_series(n):
    """Суммирует ряд чисел от 1 до n."""
    total = 0
    for i in range(1, n + 1):
        total += i
    return total

n = int(input("Введите число n для суммирования ряда от 1 до n: "))
result = sum_series(n)
print(f"Сумма чисел от 1 до {n} = {result}")

def Minmax(X, Y):
    """Сравнивает X и Y, возвращает минимум и максимум."""
    if X > Y:
        X, Y = Y, X  
    return X, Y

