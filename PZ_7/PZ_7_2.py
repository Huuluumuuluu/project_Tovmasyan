print("ЗАДАЧА 2: Слова с одинаковыми первой и последней буквой")
print("=" * 50)

text = input("Введите строку (русские заглавные буквы, слова разделены пробелами):\n")

words = text.split()

count = 0
for word in words:
    if word: 
        if word[0] == word[-1]: 
            count += 1

print(f"\nКоличество слов, начинающихся и заканчивающихся одной буквой: {count}")
